#!/usr/bin/env python3
"""Regenerate src/themes-monkeytype.ts from Monkeytype's theme list.

Usage:
  git clone --depth 1 https://github.com/monkeytypegame/monkeytype
  python3 scripts/gen-monkeytype-themes.py monkeytype/frontend/src/ts/constants/themes.ts

Monkeytype is licensed under GPL-3.0; see THIRD_PARTY_NOTICES.md.
"""
import re
import subprocess
import sys
from pathlib import Path

KEYS = ["bg", "main", "caret", "sub", "subAlt", "text", "error"]


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1])
    body = source.read_text().split("export const themes", 1)[1]
    rows = []
    for m in re.finditer(r'\n  "?([a-z0-9_]+)"?: \{(.*?)\n  \}', body, re.S):
        name, block = m.group(1), m.group(2)
        colors = dict(re.findall(r'(\w+): "(#[0-9a-fA-F]+)"', block))
        if all(k in colors for k in KEYS):
            values = ", ".join(f'"{colors[k].lower()}"' for k in KEYS)
            rows.append(f'  ["{name.replace("_", " ")}", {values}],')
    try:
        commit = subprocess.run(
            ["git", "-C", str(source.parent), "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    out = Path(__file__).resolve().parent.parent / "src" / "themes-monkeytype.ts"
    out.write_text(
        "// Generated by scripts/gen-monkeytype-themes.py from Monkeytype's theme list\n"
        f"// (https://github.com/monkeytypegame/monkeytype at {commit}, frontend/src/ts/constants/themes.ts).\n"
        "// Monkeytype is licensed under GPL-3.0; these palettes are used under that license.\n"
        "// See THIRD_PARTY_NOTICES.md. Columns: name, bg, main, caret, sub, subAlt, text, error.\n"
        "export const monkeytypeThemes: [string, string, string, string, string, string, string, string][] = [\n"
        + "\n".join(rows)
        + "\n];\n"
    )
    print(f"wrote {len(rows)} themes to {out}")


if __name__ == "__main__":
    main()
